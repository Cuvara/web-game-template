// pnpm sdk:check - ad coverage per target platform (scripts/sdk/ad-coverage.mjs).
//
// The 2026-10-21 incident: a title's integration plan listed its placements for crazygames,
// yandex and poki; the title was retargeted to yandex, crazygames and y8 with
// monetization.ad_kinds [interstitial, rewarded], and the y8 build shipped with no ad call.

import { execFileSync } from "node:child_process";
import process from "node:process";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import { stringify } from "yaml";
import { checkAdCoverage, covers, readPlan } from "../../scripts/sdk/ad-coverage.mjs";
import { checkIntegration } from "../../scripts/sdk/check-integration.mjs";

let dirs = [];
afterEach(() => {
  for (const dir of dirs) rmSync(dir, { recursive: true, force: true });
  dirs = [];
});

const PROFILES = {
  y8: { id: "y8", version: "1.3.0", capabilities: { ads: ["interstitial", "rewarded"] } },
  yandex: { id: "yandex", version: "1.4.0", capabilities: { ads: ["interstitial", "rewarded"] } },
  crazygames: {
    id: "crazygames",
    version: "1.3.0",
    capabilities: { ads: ["interstitial", "rewarded"] },
  },
  poki: { id: "poki", version: "1.0.0", capabilities: { ads: ["interstitial", "rewarded"] } },
  "generic-web": { id: "generic-web", version: "1.0.0", capabilities: { ads: [] } },
  gamevui: { id: "gamevui", version: "1.0.0", capabilities: { ads: ["interstitial"] } },
};

/** The plan exactly as the Factory's sdk step renders it (wgf_sdk/integrate.py render_plan). */
function renderPlan({ placements, adapterSubstitutes = {}, breakOnContinue = [] }) {
  const ts = (value) => JSON.stringify(value, null, 2).replace(/"(\w+)":/g, "$1:");
  return (
    "// Generated by the Factory's `sdk` workflow step from wgf:game-design:demo:1.\n" +
    "// Do not edit: change the game-design and run the step again.\n\n" +
    'import type { IntegrationPlan } from "./gameplay.js";\n\n' +
    `export const INTEGRATION_PLAN: IntegrationPlan = ${ts({
      titleId: "demo",
      placements,
      adapterSubstitutes,
      breakOnContinue,
    })};\n`
  );
}

const placement = (kind, platforms, moment = "game-over") => ({
  id: `${kind}-${moment}`,
  kind,
  moment,
  trigger: "after a lost run, a // comment-like trigger: {not code}",
  platforms,
});

function repo({ targets, adKinds, plan, omitProfiles = [] }) {
  const dir = mkdtempSync(join(tmpdir(), "sdk-ads-"));
  dirs.push(dir);
  const config = {
    game: { id: "demo", name: "Demo", version: "0.1.0" },
    engine: { type: "pixijs" },
    platforms: targets.map((id) => ({
      id,
      profile: `${id}@${PROFILES[id].version}`,
      role: "required",
    })),
    monetization: { ad_kinds: adKinds, iap: false },
  };
  writeFileSync(join(dir, "game.config.yaml"), stringify(config));
  mkdirSync(join(dir, "config/platforms"), { recursive: true });
  for (const id of targets) {
    if (omitProfiles.includes(id)) continue;
    writeFileSync(join(dir, `config/platforms/${id}.yaml`), stringify(PROFILES[id]));
  }
  if (plan !== undefined) {
    mkdirSync(join(dir, "src/platform"), { recursive: true });
    writeFileSync(join(dir, "src/platform/integration-plan.ts"), plan);
  }
  return { dir, config };
}

const INCIDENT_PLATFORMS = ["crazygames", "yandex", "poki"];

describe("sdk:check ad coverage per target platform", () => {
  it("fails the incident: plan placements for crazygames/yandex/poki, a y8 target", () => {
    const { dir, config } = repo({
      targets: ["yandex", "crazygames", "y8"],
      adKinds: ["interstitial", "rewarded"],
      plan: renderPlan({
        placements: [
          placement("interstitial", INCIDENT_PLATFORMS),
          placement("rewarded", INCIDENT_PLATFORMS),
        ],
      }),
    });
    const report = checkAdCoverage(dir, config);
    expect(report.status).toBe("fail");
    expect(report.problems).toHaveLength(2);
    const [interstitial, rewarded] = report.problems;
    // Names the platform, the ad kind and the file to regenerate.
    expect(interstitial).toMatch(/^y8: .*"interstitial".*config\/platforms\/y8\.yaml/);
    expect(interstitial).toContain("src/platform/integration-plan.ts");
    expect(interstitial).toContain("crazygames, yandex, poki");
    expect(interstitial).toMatch(/Regenerate .*--from sdk/);
    expect(rewarded).toMatch(/^y8: .*"rewarded"/);
    expect(report.checks.filter((c) => c.ok).map((c) => c.id)).toEqual([
      "ads-coverage:yandex:interstitial",
      "ads-coverage:yandex:rewarded",
      "ads-coverage:crazygames:interstitial",
      "ads-coverage:crazygames:rewarded",
    ]);
  });

  it("passes once the plan lists y8", () => {
    const listed = [...INCIDENT_PLATFORMS, "y8"];
    const { dir, config } = repo({
      targets: ["yandex", "crazygames", "y8"],
      adKinds: ["interstitial", "rewarded"],
      plan: renderPlan({
        placements: [placement("interstitial", listed), placement("rewarded", listed)],
      }),
    });
    expect(checkAdCoverage(dir, config)).toMatchObject({ status: "pass", problems: [] });
  });

  it("counts a placement for every platform (platforms: null)", () => {
    const { dir, config } = repo({
      targets: ["y8"],
      adKinds: ["interstitial"],
      plan: renderPlan({ placements: [placement("interstitial", null)] }),
    });
    expect(checkAdCoverage(dir, config).status).toBe("pass");
  });

  it("requires nothing of a platform whose profile offers no ads", () => {
    const { dir, config } = repo({
      targets: ["generic-web"],
      adKinds: ["interstitial", "rewarded"],
      plan: renderPlan({ placements: [] }),
    });
    expect(checkAdCoverage(dir, config)).toMatchObject({ status: "pass", problems: [] });
  });

  it("requires nothing for an ad kind the monetization does not commit to", () => {
    const { dir, config } = repo({
      targets: ["y8"],
      adKinds: ["interstitial"],
      plan: renderPlan({ placements: [placement("interstitial", ["y8"])] }),
    });
    const report = checkAdCoverage(dir, config);
    expect(report.status).toBe("pass");
    expect(report.checks.map((c) => c.id)).toEqual(["ads-coverage:y8:interstitial"]);

    const none = repo({ targets: ["y8"], adKinds: [], plan: renderPlan({ placements: [] }) });
    expect(checkAdCoverage(none.dir, none.config).status).toBe("pass");
  });

  it("matches the target id, not an adapter substitute", () => {
    const { dir, config } = repo({
      targets: ["gamevui"],
      adKinds: ["interstitial"],
      plan: renderPlan({
        placements: [placement("interstitial", ["generic-web"])],
        adapterSubstitutes: { gamevui: "generic-web" },
      }),
    });
    const report = checkAdCoverage(dir, config);
    expect(report.status).toBe("fail");
    expect(report.problems[0]).toMatch(/gamevui runs on the generic-web adapter/);
  });

  it("covers an interstitial through breakOnContinue, never a rewarded", () => {
    const { plan } = readPlan(renderPlan({ placements: [], breakOnContinue: ["poki"] }));
    expect(covers(plan, "interstitial", "poki")).toBe(true);
    expect(covers(plan, "rewarded", "poki")).toBe(false);
    expect(covers(plan, "interstitial", "y8")).toBe(false);
  });

  it("skips a repository the sdk step has not integrated yet", () => {
    const { dir, config } = repo({ targets: ["y8"], adKinds: ["interstitial"] });
    const report = checkAdCoverage(dir, config);
    expect(report.status).toBe("skipped");
    expect(report.problems).toEqual([]);
  });

  it("fails a target whose profile is not vendored", () => {
    const { dir, config } = repo({
      targets: ["y8"],
      adKinds: ["interstitial"],
      plan: renderPlan({ placements: [placement("interstitial", ["y8"])] }),
      omitProfiles: ["y8"],
    });
    const report = checkAdCoverage(dir, config);
    expect(report.status).toBe("fail");
    expect(report.problems[0]).toMatch(/config\/platforms\/y8\.yaml is not vendored/);
  });

  it("fails a plan it cannot read", () => {
    const { dir, config } = repo({
      targets: ["y8"],
      adKinds: ["interstitial"],
      plan: "export const SOMETHING_ELSE = 1;\n",
    });
    expect(checkAdCoverage(dir, config).status).toBe("fail");
  });

  it("reads a commented-out placement as absent", () => {
    const text = renderPlan({ placements: [placement("interstitial", ["yandex"])] }).replace(
      '"yandex"',
      '"yandex" /* , "y8" */',
    );
    const { plan } = readPlan(text);
    expect(covers(plan, "interstitial", "y8")).toBe(false);
    expect(covers(plan, "interstitial", "yandex")).toBe(true);
  });

  it("exits 1 from the CLI on the incident and 0 on this template", () => {
    const { dir } = repo({
      targets: ["yandex", "crazygames", "y8"],
      adKinds: ["interstitial", "rewarded"],
      plan: renderPlan({
        placements: [
          placement("interstitial", INCIDENT_PLATFORMS),
          placement("rewarded", INCIDENT_PLATFORMS),
        ],
      }),
    });
    const cli = resolve(import.meta.dirname, "../../scripts/sdk/check-integration.mjs");
    let status = 0;
    let stdout = "";
    try {
      execFileSync(process.execPath, [cli, "--root", dir], { stdio: "pipe" });
    } catch (error) {
      status = error.status;
      stdout = String(error.stdout);
    }
    expect(status).toBe(1);
    expect(JSON.parse(stdout)).toMatchObject({ ok: false, status: "fail" });

    const template = checkIntegration(resolve(import.meta.dirname, "../.."));
    expect(template.ok).toBe(true);
  });
});
